public class PlusVariable {
    public static void main(String[] args) {
            String name = "Java";
            int version = 21;
            int learning_hours = 40;
            boolean decision = true;
            int newVersion = version + 1;

            System.out.println("Name : " + name); // + is used to join variable with text statements
            System.out.println("Version : " + version);
            System.out.println("Current Learning Hours : " + learning_hours + " hrs");
            System.out.println("Want to become a SDE : " + decision);
            System.out.println("Version next year : " + newVersion);
    }
}
