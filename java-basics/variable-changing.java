public class VariableChanges {
    public static void main(String[] args) {
        int age = 22;
        System.out.println(age);
        age = 23;   // new value assigned to variable age
        System.out.println(age);

        int nextYearAge = age + 1;  // two variable can be used together
        System.out.println(nextYearAge);
    }
}
